// Words for kinds of place, from iD's tagging presets (ISC): for every OSM value the categories
// use (OpenMapTiles `poi` subclass), the preset names, aliases and search terms in en and de.
// More specific presets ("Pizza Restaurant", "Mosque") add their names only: their terms are
// dishes and rites. Writes src/core/placeWords.ts; run after changing the categories' values
// or updating @openstreetmap/id-tagging-schema.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { format, resolveConfig } from 'prettier';
import { TABLE } from '../src/core/categoryTable.ts';

const require = createRequire(import.meta.url);
const dist = (f) => require(`@openstreetmap/id-tagging-schema/dist/${f}`);
const presets = dist('presets.json');
const langs = ['en', 'de'].map((l) => dist(`translations/${l}.json`)[l].presets.presets);
const { version } = JSON.parse(
  readFileSync(require.resolve('@openstreetmap/id-tagging-schema/package.json'), 'utf8'),
);

const wanted = new Set(Object.values(TABLE).flatMap((c) => c.tags));
/** Words too general to name a kind of place, or that name places too ("Tiergarten", "Wedding"). */
const STOP = new Set([
  ...['shop', 'store', 'laden', 'geschaft', 'market', 'markt', 'place', 'ort'],
  ...['tiergarten', 'parish', 'hamburgerstand', 'wedding clothes store'],
]);

/** The OSM keys whose values OpenMapTiles keeps as the `poi` subclass. */
const KEYS = ['amenity', 'shop', 'leisure', 'tourism', 'historic', 'landuse', 'railway', 'highway'];

const fold = (s) =>
  s
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/ß/g, 'ss')
    .replace(/\(.*?\)/g, '')
    .replace(/\s+/g, ' ')
    .trim();

/** Aliases and terms come as a list or as one string. */
const list = (v) => (Array.isArray(v) ? v : (v ?? '').split(/[,\n]/));

const words = new Map();
for (const [id, preset] of Object.entries(presets)) {
  const key = KEYS.find((k) => k in preset.tags);
  const subclass = key && preset.tags[key];
  if (!wanted.has(subclass)) continue;
  const own = Object.keys(preset.tags).length === 1;
  const set = words.get(subclass) ?? new Set();
  for (const names of langs) {
    const p = names[id];
    if (!p) continue;
    const all = [
      // "Train Station (Halt / Request)": the words in brackets explain, they do not name.
      ...(p.name ?? '').replace(/\(.*?\)/g, '').split(/[/,]/),
      ...list(p.aliases),
      ...(own ? list(p.terms) : []),
    ];
    for (const w of all.map(fold)) {
      if (w.length >= 2 && !w.includes('|') && !STOP.has(w)) set.add(w);
    }
  }
  words.set(subclass, set);
}

const entries = [...words]
  .filter(([, set]) => set.size)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([sub, set]) => `  ${JSON.stringify(sub)}: ${JSON.stringify([...set].sort().join('|'))},`);

const out = 'src/core/placeWords.ts';
const code = `// Generated by scripts/place-words.mjs from @openstreetmap/id-tagging-schema ${version} (ISC).
// Do not edit; run \`npm run words\`.

/** Words for each OSM value (OpenMapTiles \`poi\` subclass), en and de, folded, \`|\`-separated. */
export const PLACE_WORDS: Record<string, string> = {
${entries.join('\n')}
};
`;
writeFileSync(out, await format(code, { ...(await resolveConfig(out)), filepath: out }));
console.log(`${out}: ${entries.length} subclasses`);
